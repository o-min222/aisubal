-- A149: read-only catalog query that renders the app schema (public, anon_private, the auth.users
-- signup trigger, storage policies, bucket config, cron jobs) as DDL rows. No table data, no secrets.
-- Run with search_path=pg_catalog so every name comes back schema-qualified.
-- Output: (sec, key, ddl); scripts/baseline-assemble.mjs orders and writes the baseline file.
set search_path to pg_catalog;
with
ns as (select oid, nspname from pg_namespace where nspname in ('public','anon_private')),
rel as (
  select c.oid, c.relname, c.relkind, c.relpersistence, c.relrowsecurity, c.relforcerowsecurity, c.relacl, c.relowner,
         n.nspname, format('%I.%I', n.nspname, c.relname) as q
  from pg_class c join ns n on n.oid = c.relnamespace
  where c.relkind in ('r','p','v','m','S')
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
),
fn as (
  select p.oid, p.proacl, p.proowner, p.oid::regprocedure::text as sig, n.nspname
  from pg_proc p join ns n on n.oid = p.pronamespace
  where p.prokind in ('f','p') and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
rows as (
  -- 10 standalone / serial sequences (identity sequences come with their column)
  select 10 sec, r.q key,
    format('CREATE SEQUENCE %s AS %s START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s%s;',
      r.q, format_type(s.seqtypid, null), s.seqstart, s.seqincrement, s.seqmin, s.seqmax, s.seqcache, case when s.seqcycle then ' CYCLE' else '' end) ddl
  from rel r join pg_sequence s on s.seqrelid = r.oid
  where r.relkind = 'S' and not exists (select 1 from pg_depend d where d.objid = r.oid and d.deptype = 'i')
  union all
  -- 20 tables (columns, generated, identity, not null; defaults come after functions)
  select 20, r.q,
    format('CREATE %sTABLE %s (%s);', case when r.relpersistence = 'u' then 'UNLOGGED ' else '' end, r.q,
      coalesce((select string_agg(
        format(E'\n  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case when a.attcollation <> t.typcollation and a.attcollation <> 0 then ' COLLATE ' || (select format('%I.%I', cn.nspname, co.collname) from pg_collation co join pg_namespace cn on cn.oid = co.collnamespace where co.oid = a.attcollation) else '' end
        || case when a.attgenerated = 's' then ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED' else '' end
        || case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY' when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end
        || case when a.attnotnull then ' NOT NULL' else '' end, ',' order by a.attnum)
       from pg_attribute a join pg_type t on t.oid = a.atttypid
       left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
       where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped), '') || E'\n')
  from rel r where r.relkind in ('r','p')
  union all
  -- 30 functions and procedures
  select 30, f.sig, pg_get_functiondef(f.oid) || ';' from fn f
  union all
  -- 35 views
  select 35, r.q, format(E'CREATE %s %s AS\n%s', case r.relkind when 'm' then 'MATERIALIZED VIEW' else 'VIEW' end, r.q, rtrim(pg_get_viewdef(r.oid), ';')) || ';'
  from rel r where r.relkind in ('v','m')
  union all
  -- 40 column defaults
  select 40, r.q || '.' || a.attname, format('ALTER TABLE ONLY %s ALTER COLUMN %I SET DEFAULT %s;', r.q, a.attname, pg_get_expr(ad.adbin, ad.adrelid))
  from rel r join pg_attribute a on a.attrelid = r.oid join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  where a.attgenerated = '' and not a.attisdropped
  union all
  -- 45 serial sequence ownership
  select 45, r.q, format('ALTER SEQUENCE %s OWNED BY %s.%I;', r.q, (select format('%I.%I', tn.nspname, tc.relname) from pg_class tc join pg_namespace tn on tn.oid = tc.relnamespace where tc.oid = d.refobjid), a.attname)
  from rel r join pg_depend d on d.objid = r.oid and d.deptype = 'a' and d.classid = 'pg_class'::regclass and d.refclassid = 'pg_class'::regclass
  join pg_attribute a on a.attrelid = d.refobjid and a.attnum = d.refobjsubid
  where r.relkind = 'S'
  union all
  -- 50 primary/unique/check/exclusion constraints, 55 foreign keys
  select case when co.contype = 'f' then 55 else 50 end,
    r.q || '.' || case co.contype when 'p' then '1' when 'u' then '2' when 'x' then '3' else '4' end || co.conname,
    format('ALTER TABLE ONLY %s ADD CONSTRAINT %I %s;', r.q, co.conname, pg_get_constraintdef(co.oid))
  from rel r join pg_constraint co on co.conrelid = r.oid where co.contype in ('p','u','c','x','f') and co.conislocal
  union all
  -- 60 indexes that do not back a constraint
  select 60, r.q || '.' || ic.relname, pg_get_indexdef(i.indexrelid) || ';'
  from rel r join pg_index i on i.indrelid = r.oid join pg_class ic on ic.oid = i.indexrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid and co.contype in ('p','u','x'))
  union all
  -- 65 triggers on app tables and the auth.users signup trigger
  select 65, format('%I.%I.%I', n.nspname, c.relname, t.tgname), pg_get_triggerdef(t.oid) || ';'
         || case t.tgenabled when 'D' then format(E'\nALTER TABLE %I.%I DISABLE TRIGGER %I;', n.nspname, c.relname, t.tgname) else '' end
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not t.tgisinternal and (n.nspname in ('public','anon_private') or (n.nspname = 'auth' and c.relname = 'users'))
  union all
  -- 70 row level security
  select 70, r.q, format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY;', r.q) || case when r.relforcerowsecurity then format(' ALTER TABLE %s FORCE ROW LEVEL SECURITY;', r.q) else '' end
  from rel r where r.relrowsecurity
  union all
  -- 75 policies (app schemas + storage)
  select 75, format('%I.%I.%I', n.nspname, c.relname, p.polname),
    format('CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', p.polname, n.nspname, c.relname,
      case when p.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
      case p.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end,
      case when p.polroles = '{0}' then 'PUBLIC' else (select string_agg(quote_ident(rolname), ', ' order by rolname) from pg_roles where oid = any(p.polroles)) end,
      case when p.polqual is not null then E'\n  USING (' || pg_get_expr(p.polqual, p.polrelid) || ')' else '' end,
      case when p.polwithcheck is not null then E'\n  WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')' else '' end)
  from pg_policy p join pg_class c on c.oid = p.polrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in ('public','anon_private','storage')
  union all
  -- 80 relation privileges: reset Supabase defaults, then grant exactly what prod has
  select 80, r.q,
    format('REVOKE ALL ON %s FROM PUBLIC, anon, authenticated, service_role;', r.q)
    || coalesce((select string_agg(format(E'\nGRANT %s ON %s TO %s%s;', x.privilege_type, r.q,
          case when x.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(x.grantee)) end,
          case when x.is_grantable then ' WITH GRANT OPTION' else '' end), '' order by pg_get_userbyid(x.grantee), x.privilege_type)
       from aclexplode(coalesce(r.relacl, acldefault((case when r.relkind = 'S' then 's' else 'r' end)::"char", r.relowner))) x where x.grantee <> r.relowner), '')
  from rel r
  union all
  -- 81 column privileges
  select 81, r.q || '.' || a.attname,
    string_agg(format('GRANT %s (%I) ON %s TO %s;', x.privilege_type, a.attname, r.q,
      case when x.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(x.grantee)) end), E'\n' order by pg_get_userbyid(x.grantee), x.privilege_type)
  from rel r join pg_attribute a on a.attrelid = r.oid, aclexplode(a.attacl) x
  where a.attacl is not null and not a.attisdropped
  group by r.q, a.attname
  union all
  -- 82 function privileges
  select 82, f.sig,
    format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated, service_role;', f.sig)
    || coalesce((select string_agg(format(E'\nGRANT EXECUTE ON FUNCTION %s TO %s;', f.sig,
          case when x.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(x.grantee)) end), '' order by pg_get_userbyid(x.grantee))
       from aclexplode(coalesce(f.proacl, acldefault('f'::"char", f.proowner))) x where x.grantee <> f.proowner), '')
  from fn f
  union all
  -- 85 schema privileges for anon_private
  select 85, n.nspname, format('REVOKE ALL ON SCHEMA %I FROM PUBLIC, anon, authenticated, service_role;', n.nspname)
    || coalesce((select string_agg(format(E'\nGRANT %s ON SCHEMA %I TO %s;', x.privilege_type, n.nspname, case when x.grantee = 0 then 'PUBLIC' else quote_ident(pg_get_userbyid(x.grantee)) end), '' order by pg_get_userbyid(x.grantee), x.privilege_type)
       from aclexplode(sn.nspacl) x where x.grantee <> sn.nspowner), '')
  from ns n join pg_namespace sn on sn.oid = n.oid where n.nspname = 'anon_private'
  union all
  -- 86 default privileges postgres sets in public
  select 86, d.defaclobjtype::text,
    format('ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON %s FROM anon, authenticated, service_role;', k.word)
    || coalesce((select string_agg(format(E'\nALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT %s ON %s TO %s;', x.privilege_type, k.word, quote_ident(pg_get_userbyid(x.grantee))), '' order by pg_get_userbyid(x.grantee), x.privilege_type)
       from aclexplode(d.defaclacl) x), '')
  from pg_default_acl d join pg_namespace n on n.oid = d.defaclnamespace
  join (values ('r','TABLES'),('S','SEQUENCES'),('f','FUNCTIONS')) k(t, word) on k.t = d.defaclobjtype::text
  where n.nspname = 'public' and pg_get_userbyid(d.defaclrole) = 'postgres'
  union all
  -- 88 comments
  select 88, r.q, format('COMMENT ON %s %s IS %L;', case r.relkind when 'v' then 'VIEW' when 'm' then 'MATERIALIZED VIEW' when 'S' then 'SEQUENCE' else 'TABLE' end, r.q, de.description)
  from rel r join pg_description de on de.objoid = r.oid and de.classoid = 'pg_class'::regclass and de.objsubid = 0
  union all
  select 88, r.q || '.' || a.attname, format('COMMENT ON COLUMN %s.%I IS %L;', r.q, a.attname, de.description)
  from rel r join pg_attribute a on a.attrelid = r.oid join pg_description de on de.objoid = r.oid and de.classoid = 'pg_class'::regclass and de.objsubid = a.attnum
  union all
  select 88, f.sig, format('COMMENT ON FUNCTION %s IS %L;', f.sig, de.description)
  from fn f join pg_description de on de.objoid = f.oid and de.classoid = 'pg_proc'::regclass
  union all
  -- 90 storage bucket configuration (no objects)
  select 90, b.id, format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %s, %s, %s) ON CONFLICT (id) DO NOTHING;',
    b.id, b.name, case when b.public then 'true' else 'false' end, coalesce(b.file_size_limit::text, 'NULL'), coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'NULL'))
  from storage.buckets b
  union all
  -- 95 cron jobs (commands are plain function calls)
  select 95, j.jobname, format('SELECT cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command) from cron.job j
)
select sec, key, ddl from rows
where sec between :lo and :hi
order by sec, key;
