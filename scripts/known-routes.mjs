#!/usr/bin/env node
/**
 * A149: the page and route-handler paths under src/app (route groups stripped, no /api, no the
 * (app)/[...missing] catch-all) → src/lib/known-routes.ts. The middleware uses it so a signed-out
 * visit to a URL no page serves gets a real 404 instead of the sign-in redirect.
 *   node scripts/known-routes.mjs --write   (tests/a149-known-routes.test.ts fails when it is stale)
 */
import fs from 'node:fs'
import path from 'node:path'

const APP = 'src/app'
export const OUT = 'src/lib/known-routes.ts'
const ROUTE_FILE = /^(page|route)\.(tsx?|jsx?)$/

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else if (ROUTE_FILE.test(e.name)) out.push(path.relative(APP, dir))
  }
  return out
}

/** One route dir → a regex source for its URL, or null when it is not served to browsers by a page. */
export function routePattern(dir) {
  const segs = dir.split(path.sep).filter(Boolean).filter((s) => !/^\(.*\)$/.test(s) && !s.startsWith('@'))
  if (segs[0] === 'api') return null
  if (segs.length === 1 && segs[0] === '[...missing]') return null
  if (segs.some((s) => s.startsWith('_'))) return null
  let re = ''
  for (const s of segs) {
    if (/^\[\[\.\.\..+\]\]$/.test(s)) re += '(?:/.*)?'
    else if (/^\[\.\.\..+\]$/.test(s)) re += '/.+'
    else if (/^\[.+\]$/.test(s)) re += '/[^/]+'
    else re += '/' + s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  }
  return '^' + (re ? re + '/?' : '/') + '$'
}

export function render() {
  const pats = [...new Set(walk(APP).map(routePattern).filter(Boolean))].sort()
  return `// Generated by scripts/known-routes.mjs --write from the page/route files under src/app. Do not edit.
// A149: a signed-out request for a path outside this list gets a 404 instead of the sign-in redirect.
const PATTERNS: RegExp[] = [
${pats.map((p) => `  /${p.replace(/\//g, '\\/')}/,`).join('\n')}
]

/** True when some page or route handler under src/app serves this path (dynamic segments match anything). */
export function isKnownRoute(pathname: string): boolean {
  return PATTERNS.some((re) => re.test(pathname))
}
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render()
  if (process.argv.includes('--write')) fs.writeFileSync(OUT, text)
  else process.stdout.write(text)
}
